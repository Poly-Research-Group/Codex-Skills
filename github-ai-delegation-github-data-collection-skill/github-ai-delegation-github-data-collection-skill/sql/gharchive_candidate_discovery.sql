-- GH Archive candidate discovery for visible AI delegation traces.
-- Parameterize @start_yyyymm, @end_yyyymm, @start_ts, @end_ts.
-- Output should be hydrated through GitHub API before use.

SELECT
  created_at AS candidate_event_time_utc,
  type AS event_type,
  repo.name AS repo_full_name,
  actor.login AS candidate_actor_login,
  JSON_VALUE(payload, '$.action') AS action,
  JSON_VALUE(payload, '$.pull_request.html_url') AS pr_url,
  SAFE_CAST(JSON_VALUE(payload, '$.pull_request.number') AS INT64) AS pull_number,
  JSON_VALUE(payload, '$.pull_request.user.login') AS pr_author_login,
  JSON_VALUE(payload, '$.pull_request.user.type') AS pr_author_type,
  JSON_VALUE(payload, '$.pull_request.title') AS pr_title,
  JSON_VALUE(payload, '$.pull_request.body') AS pr_body,
  JSON_VALUE(payload, '$.issue.html_url') AS issue_url,
  SAFE_CAST(JSON_VALUE(payload, '$.issue.number') AS INT64) AS issue_number,
  JSON_VALUE(payload, '$.comment.html_url') AS comment_url,
  JSON_VALUE(payload, '$.comment.body') AS comment_body,
  CASE
    WHEN REGEXP_CONTAINS(LOWER(TO_JSON_STRING(payload)), r'(^|[^a-z0-9_-])@copilot([^a-z0-9_-]|$)') THEN 'exact_invocation_candidate'
    WHEN REGEXP_CONTAINS(LOWER(actor.login), r'(copilot|codex|claude|devin|cursor)') THEN 'platform_attributed_ai_candidate'
    WHEN REGEXP_CONTAINS(LOWER(JSON_VALUE(payload, '$.pull_request.user.login')), r'(copilot|codex|claude|devin|cursor)') THEN 'platform_attributed_ai_candidate'
    WHEN REGEXP_CONTAINS(LOWER(TO_JSON_STRING(payload)), r'(ai[- ]generated|llm[- ]generated|generated with copilot|generated by chatgpt|claude code|cursor|devin|codex)') THEN 'self_disclosure_candidate'
    ELSE 'unknown_ai_related_candidate'
  END AS candidate_signal_family,
  TO_JSON_STRING(payload) AS payload_json
FROM `githubarchive.month.*`
WHERE _TABLE_SUFFIX BETWEEN @start_yyyymm AND @end_yyyymm
  AND created_at BETWEEN TIMESTAMP(@start_ts) AND TIMESTAMP(@end_ts)
  AND type IN (
    'PullRequestEvent',
    'IssuesEvent',
    'IssueCommentEvent',
    'PullRequestReviewEvent',
    'PullRequestReviewCommentEvent',
    'PushEvent'
  )
  AND (
    REGEXP_CONTAINS(LOWER(TO_JSON_STRING(payload)), r'(^|[^a-z0-9_-])@copilot([^a-z0-9_-]|$)')
    OR REGEXP_CONTAINS(LOWER(TO_JSON_STRING(payload)), r'(ai[- ]generated|llm[- ]generated|generated with copilot|generated by chatgpt|claude code|cursor|devin|codex)')
    OR REGEXP_CONTAINS(LOWER(actor.login), r'(copilot|codex|claude|devin|cursor)')
    OR REGEXP_CONTAINS(LOWER(JSON_VALUE(payload, '$.pull_request.user.login')), r'(copilot|codex|claude|devin|cursor)')
  );
